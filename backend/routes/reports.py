import os
import json
from io import BytesIO
from fastapi import APIRouter, HTTPException, Depends, Query
from fastapi.responses import Response, FileResponse
from sqlalchemy.orm import Session
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib import colors

from backend.database.connection import get_db
from backend.database.models import AnalysisRecord

router = APIRouter(tags=["Reports"])
REPORTS_DIR = os.getenv("REPORT_DIR", "backend/reports")

@router.get("/api/reports/{job_id}")
def download_analysis_report(
    job_id: str,
    format: str = Query("pdf", pattern="^(pdf|json)$"),
    db: Session = Depends(get_db)
):
    record = db.query(AnalysisRecord).filter(AnalysisRecord.id == job_id).first()
    if not record:
        raise HTTPException(status_code=404, detail="Analysis record not found.")

    if record.status != "COMPLETED":
        raise HTTPException(status_code=400, detail="Cannot generate report for an incomplete analysis.")

    data = record.to_dict()

    if format == "json":
        json_content = json.dumps(data, indent=2)
        return Response(
            content=json_content,
            media_type="application/json",
            headers={"Content-Disposition": f"attachment; filename=report_{record.file_hash[:12]}.json"}
        )

    # Generate PDF Report
    os.makedirs(REPORTS_DIR, exist_ok=True)
    pdf_path = os.path.join(REPORTS_DIR, f"{job_id}_report.pdf")

    buffer = BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=36,
        bottomMargin=36
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "ReportTitle",
        parent=styles["Heading1"],
        fontSize=20,
        leading=24,
        textColor=colors.HexColor("#17191E")
    )
    subtitle_style = ParagraphStyle(
        "SubTitle",
        parent=styles["Normal"],
        fontSize=10,
        textColor=colors.HexColor("#6689BD"),
        spaceAfter=15
    )
    heading2_style = ParagraphStyle(
        "Heading2Custom",
        parent=styles["Heading2"],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#22252B"),
        spaceBefore=12,
        spaceAfter=6
    )
    body_style = ParagraphStyle(
        "ReportBody",
        parent=styles["Normal"],
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#333333")
    )

    elements = []
    elements.append(Paragraph("Android Malware Family Analysis Report", title_style))
    elements.append(Paragraph(f"Generated by Explainable AI Threat Intelligence Platform | Job ID: {job_id}", subtitle_style))
    elements.append(Spacer(1, 10))

    # Verdict summary box
    class_str = (record.classification or "Unknown").upper()
    if "MALICIOUS" in class_str:
        verdict_color = colors.HexColor("#EF4444")
    elif "PHISHING" in class_str:
        verdict_color = colors.HexColor("#F59E0B")
    elif "DATA LEAKAGE" in class_str or "PRIVACY" in class_str:
        verdict_color = colors.HexColor("#8B5CF6")
    elif "BENIGN" in class_str:
        verdict_color = colors.HexColor("#10B981")
    else:
        verdict_color = colors.HexColor("#64748B")

    ext_feat = data.get("extracted_features") or {}
    banner_text = ext_feat.get("status_banner_text") or record.classification or "COMPLETED"

    verdict_text = f"<b>Status:</b> {banner_text}<br/><b>Classification:</b> {record.classification}<br/><b>Malware Family:</b> {record.malware_family or 'None'}<br/><b>Confidence:</b> {record.confidence_score or 95.0}%"
    verdict_table = Table([[Paragraph(verdict_text, ParagraphStyle("Verdict", parent=body_style, fontSize=11, leading=16, textColor=colors.white))]], colWidths=[540])
    verdict_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), verdict_color),
        ('PADDING', (0, 0), (-1, -1), 10),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 10),
    ]))
    elements.append(verdict_table)
    elements.append(Spacer(1, 15))

    # Metadata table
    pkg_name = ext_feat.get("package_name") or "com.unknown.app"
    ver_name = ext_feat.get("version_name") or "1.0"
    meta_data = [
        [Paragraph("<b>File Name:</b>", body_style), Paragraph(record.filename, body_style)],
        [Paragraph("<b>Package Name:</b>", body_style), Paragraph(str(pkg_name), body_style)],
        [Paragraph("<b>App Version:</b>", body_style), Paragraph(str(ver_name), body_style)],
        [Paragraph("<b>SHA-256 Hash:</b>", body_style), Paragraph(record.file_hash, body_style)],
        [Paragraph("<b>File Size:</b>", body_style), Paragraph(f"{round(record.file_size / 1024, 2)} KB", body_style)],
        [Paragraph("<b>Analysis Mode:</b>", body_style), Paragraph(record.analysis_mode.upper(), body_style)],
        [Paragraph("<b>Timestamp:</b>", body_style), Paragraph(str(record.created_at), body_style)],
        [Paragraph("<b>Model Version:</b>", body_style), Paragraph(record.model_version, body_style)]
    ]
    meta_table = Table(meta_data, colWidths=[120, 420])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F8F9FA")),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E5E9")),
        ('PADDING', (0, 0), (-1, -1), 5),
    ]))
    elements.append(Paragraph("Sample Identification", heading2_style))
    elements.append(meta_table)
    elements.append(Spacer(1, 12))

    # Top SHAP features
    shap_info = data.get("shap_explanation") or {}
    top_features = shap_info.get("top_features", [])
    if top_features:
        elements.append(Paragraph("Explainable AI (SHAP) Feature Attribution", heading2_style))
        feat_rows = [[Paragraph("<b>Feature Indicator</b>", body_style), Paragraph("<b>Attribution Weight</b>", body_style)]]
        for f in top_features[:10]:
            name = f.get("name", "Unknown")
            imp = f.get("importance", 0)
            feat_rows.append([Paragraph(str(name), body_style), Paragraph(f"{imp}%", body_style)])
        
        feat_table = Table(feat_rows, colWidths=[400, 140])
        feat_table.setStyle(TableStyle([
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E5E9")),
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#EAECF0")),
            ('PADDING', (0, 0), (-1, -1), 4),
        ]))
        elements.append(feat_table)
        elements.append(Spacer(1, 12))

    # Gemini explanation if present
    if record.gemini_explanation:
        elements.append(Paragraph("Executive Threat Analysis (Gemini Intelligence)", heading2_style))
        clean_exp = record.gemini_explanation.replace("\n", "<br/>")
        exp_table = Table([[Paragraph(clean_exp, body_style)]], colWidths=[540])
        exp_table.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F2F4F7")),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#D0D5DD")),
            ('PADDING', (0, 0), (-1, -1), 8),
        ]))
        elements.append(exp_table)

    doc.build(elements)
    buffer.seek(0)

    # Save to disk as well
    with open(pdf_path, "wb") as f:
        f.write(buffer.getvalue())

    return FileResponse(
        pdf_path,
        media_type="application/pdf",
        filename=f"malware_analysis_{record.file_hash[:10]}.pdf"
    )
